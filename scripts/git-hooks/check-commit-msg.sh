#!/bin/sh
# Enforce Conventional Commits and short messages.
#
# Usage: check-commit-msg.sh <path-to-commit-message-file>   (git commit-msg hook)
#
# Rules
#   - header: <type>(<optional scope>)<optional !>: <description>
#     types: build chore ci docs feat fix perf refactor revert style test
#   - header at most 72 characters    (git config hooks.commitHeaderMax <n>)
#   - blank line between header and body
#   - body lines at most 100 characters (git config hooks.commitBodyLineMax <n>);
#     lines with a URL and trailers such as "Co-Authored-By:" are exempt
# Merge, revert, fixup!, squash! and amend! messages generated by git are accepted.

set -u

MSG_FILE=${1:?usage: check-commit-msg.sh <commit message file>}

HEADER_MAX=$(git config --get hooks.commitHeaderMax || echo 72)
BODY_LINE_MAX=$(git config --get hooks.commitBodyLineMax || echo 100)
TYPES='build|chore|ci|docs|feat|fix|perf|refactor|revert|style|test'

# Drop comment lines and everything below the scissors line used by "git commit -v".
CLEAN=$(sed -e '/^# -\{24\} >8 -\{24\}$/,$d' -e '/^#/d' "$MSG_FILE")

HEADER=$(printf '%s\n' "$CLEAN" | sed -n '/[^[:space:]]/{p;q;}')

fail() {
  {
    echo "Commit message rejected: $1"
    echo
    echo "  Header: $HEADER"
    echo
    echo "Expected: <type>(<scope>): <short description>, at most $HEADER_MAX characters"
    echo "Types:    ${TYPES}" | tr '|' ' '
    echo "Examples: feat(garmin): import uppercase .FIT files"
    echo "          fix(desktop): release recalculation lock on error"
    echo "          docs: add architecture pages"
  } >&2
  exit 1
}

[ -n "$HEADER" ] || fail "the message is empty"

case "$HEADER" in
  "Merge "* | "Revert \""* | "fixup! "* | "squash! "* | "amend! "*) exit 0 ;;
esac

printf '%s' "$HEADER" | grep -Eq "^($TYPES)(\([A-Za-z0-9._/,-]+\))?!?: [^[:space:]].*$" ||
  fail "the header does not follow Conventional Commits"

HEADER_LEN=$(printf '%s' "$HEADER" | wc -m | tr -d ' ')
[ "$HEADER_LEN" -le "$HEADER_MAX" ] ||
  fail "the header is $HEADER_LEN characters long (maximum $HEADER_MAX)"

# Body checks: the lines after the header.
BODY_REPORT=$(printf '%s\n' "$CLEAN" | awk -v max="$BODY_LINE_MAX" '
  !seen && /[^[:space:]]/ { seen = 1; header_nr = NR; next }
  !seen { next }
  NR == header_nr + 1 && /[^[:space:]]/ { print "NOBLANK"; exit }
  /https?:\/\// || /^[A-Za-z][A-Za-z-]*: / { next }
  length($0) > max { printf "  line %d is %d characters: %.60s...\n", NR, length($0), $0 }
')

case "$BODY_REPORT" in
  NOBLANK*) fail "leave a blank line between the header and the body" ;;
  "") ;;
  *)
    {
      echo "Commit message rejected: body lines must be at most $BODY_LINE_MAX characters."
      printf '%s\n' "$BODY_REPORT"
    } >&2
    exit 1
    ;;
esac

exit 0
